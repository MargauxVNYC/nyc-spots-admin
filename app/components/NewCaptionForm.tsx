"use client";

import { useState } from "react";
import { useRouter } from "next/navigation";
import { createClient } from "../../lib/supabase/client";
import { VIBES, type VibeKey } from "../../lib/vibes";

type AiMeta = { prompt: string; model: string; original: string };

export default function NewCaptionForm({ spots }: { spots: { id: number; name: string }[] }) {
    const router = useRouter();
    const supabase = createClient();

    const [open, setOpen] = useState(false);
    const [spotId, setSpotId] = useState(spots[0]?.id ?? 0);
    const [vibe, setVibe] = useState<VibeKey>("online");
    const [text, setText] = useState("");
    const [ai, setAi] = useState<AiMeta | null>(null);
    const [generating, setGenerating] = useState(false);
    const [saving, setSaving] = useState(false);
    const [message, setMessage] = useState<{ kind: "error" | "ok"; text: string } | null>(null);

    async function generate() {
        setGenerating(true);
        setMessage(null);
        const res = await fetch("/api/generate", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ spotId, vibe }),
        });
        const data = await res.json().catch(() => ({}));
        setGenerating(false);

        if (!res.ok) {
            setMessage({ kind: "error", text: data.error ?? "Something went wrong." });
            return;
        }
        setText(data.caption);
        setAi({ prompt: data.prompt, model: data.model, original: data.caption });
    }

    async function save() {
        const caption = text.trim();
        if (!caption) {
            setMessage({ kind: "error", text: "Write or generate a caption first." });
            return;
        }
        setSaving(true);
        setMessage(null);

        const { error } = await supabase.from("generations").insert({
            spot_id: spotId,
            vibe,
            caption,
            prompt: ai?.prompt ?? "Written manually by an admin (no AI prompt).",
            model: ai ? (caption === ai.original ? ai.model : `${ai.model} (edited)`) : "manual",
        });

        setSaving(false);
        if (error) {
            setMessage({ kind: "error", text: error.message });
            return;
        }
        setText("");
        setAi(null);
        setMessage({ kind: "ok", text: "Caption created. It's live in the NYC Spots feed." });
        router.refresh();
    }

    if (!open) {
        return (
            <button className="btn btn-accent" onClick={() => setOpen(true)}>
                ＋ New caption
            </button>
        );
    }

    return (
        <section className="panel new-form">
            <div className="panel-head">
                <h2 className="panel-title">＋ New caption</h2>
                <button className="chip-btn" onClick={() => setOpen(false)}>Close</button>
            </div>

            <div className="form-grid">
                <label>
                    <span className="field-label">Spot</span>
                    <select className="select" value={spotId} onChange={(e) => setSpotId(Number(e.target.value))}>
                        {spots.map((s) => (
                            <option key={s.id} value={s.id}>{s.name}</option>
                        ))}
                    </select>
                </label>
                <label>
                    <span className="field-label">Vibe</span>
                    <select className="select" value={vibe} onChange={(e) => setVibe(e.target.value as VibeKey)}>
                        {(Object.keys(VIBES) as VibeKey[]).map((k) => (
                            <option key={k} value={k}>{VIBES[k].emoji} {VIBES[k].label}</option>
                        ))}
                    </select>
                </label>
            </div>

            <span className="field-label">Caption</span>
            <textarea
                className="input edit-area"
                rows={2}
                maxLength={300}
                placeholder="Write a caption, or generate one with AI"
                value={text}
                onChange={(e) => setText(e.target.value)}
            />
            {ai && (
                <p className="soft cell-sub">
                    Generated by <code className="model-code">{ai.model}</code>
                    {text.trim() !== ai.original && " · edited"}
                </p>
            )}

            <div className="form-actions">
                <button className="btn" onClick={generate} disabled={generating || !spotId}>
                    {generating ? "Generating…" : "✨ Generate with AI"}
                </button>
                <button className="btn btn-accent" onClick={save} disabled={saving || !text.trim()}>
                    {saving ? "Saving…" : "Save caption"}
                </button>
            </div>

            {message && (
                <p className={message.kind === "error" ? "error-text" : "ok-text"}>{message.text}</p>
            )}
        </section>
    );
}